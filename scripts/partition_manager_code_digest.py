"""The digest Partition Manager certification evidence is bound to.

The freeze rule is one sentence: docs and the site may change after a freeze, and code may not. So
this hashes every tracked file except docs, evidence and the configuration of tools that do not
build anything, and a change to any other tracked file, shipped or not, invalidates evidence.

Git turns line endings into CRLF on a Windows checkout and leaves them as LF on another, so every
file is hashed with CRLF read as LF. The same commit gives the same digest on a workstation, in a
guest and on a clean CI clone. A change that only swaps a file's line endings does not count, which
is the point.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

EXCLUDED_PREFIXES = (
    ".agents/",
    ".claude/",
    ".codex/",
    ".github/",
    ".vscode/",
    "artifacts/",
    "docs/",
)
EXCLUDED_NAMES = frozenset(
    {
        ".gitattributes",
        ".gitignore",
        ".gitleaks.toml",
        ".gitleaksignore",
        ".pre-commit-config.yaml",
        "LICENSE",
    }
)
EXCLUDED_SUFFIXES = (".md",)


class DigestError(RuntimeError):
    """The digest cannot be worked out, so nothing may be bound to it."""


def is_code(path: str) -> bool:
    """Whether a tracked path counts as code under the freeze rule."""
    return not (
        path.startswith(EXCLUDED_PREFIXES)
        or path in EXCLUDED_NAMES
        or path.endswith(EXCLUDED_SUFFIXES)
    )


def run_git(root: Path, *arguments: str) -> bytes:
    completed = subprocess.run(
        ["git", "-C", str(root), *arguments], capture_output=True, check=False
    )
    if completed.returncode != 0:
        message = completed.stderr.decode("utf-8", "replace").strip()
        raise DigestError(f"git {' '.join(arguments)} failed: {message}")
    return completed.stdout


def tracked_code(root: Path) -> list[str]:
    listed = run_git(root, "ls-files", "-z").decode("utf-8").split("\0")
    paths = sorted(path for path in listed if path and is_code(path))
    if not paths:
        raise DigestError(f"No tracked code under {root}")
    return paths


def normalized_bytes(path: Path) -> bytes:
    return path.read_bytes().replace(b"\r\n", b"\n")


def digest_of(root: Path, paths: list[str]) -> str:
    total = hashlib.sha256()
    for relative in paths:
        full = root / relative
        if not full.is_file():
            raise DigestError(f"Tracked file is missing from the working tree: {relative}")
        content = hashlib.sha256(normalized_bytes(full)).hexdigest()
        total.update(f"{relative}\0{content}\n".encode("utf-8"))
    return total.hexdigest()


def code_is_dirty(root: Path, paths: list[str]) -> bool:
    """Whether a code file differs from HEAD, taking line endings as git's filters do."""
    listed = run_git(root, "status", "--porcelain", "-z", "--no-renames", "--", ".")
    wanted = set(paths)
    for entry in listed.decode("utf-8").split("\0"):
        if entry and not entry.startswith("??") and entry[3:] in wanted:
            return True
    return False


def describe(root: Path) -> dict[str, object]:
    paths = tracked_code(root)
    return {
        "code_digest": digest_of(root, paths),
        "code_commit": run_git(root, "rev-parse", "HEAD").decode("ascii").strip(),
        "code_dirty": code_is_dirty(root, paths),
        "file_count": len(paths),
    }


def header_text(description: dict[str, object]) -> str:
    return (
        "// Generated by scripts/partition_manager_code_digest.py. Do not edit.\n"
        "#pragma once\n"
        f'#define SAK_CODE_DIGEST "{description["code_digest"]}"\n'
        f'#define SAK_CODE_COMMIT "{description["code_commit"]}"\n'
        f"#define SAK_CODE_DIRTY {'true' if description['code_dirty'] else 'false'}\n"
    )


def write_if_changed(path: Path, text: str) -> None:
    """Leaves an unchanged header's timestamp alone, so nothing rebuilds for no reason."""
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--header", type=Path, help="write the digest as a C header here")
    arguments = parser.parse_args()
    try:
        description = describe(arguments.root.resolve())
    except DigestError as error:
        print(error, file=sys.stderr)
        return 2
    if arguments.header is not None:
        write_if_changed(arguments.header, header_text(description))
    print(json.dumps(description))
    return 0


if __name__ == "__main__":
    sys.exit(main())
